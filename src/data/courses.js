// Seed catalog of publicly bookable golf courses.
//
// This is the "public" half of the app's data: it ships with the bundle, is the
// same for every user, and is never written to. Anything a golfer creates on top
// of it (ratings, reviews, bookings, play log) lives in the private on-device
// database in services/db.js and never leaves the device.
//
// Ratings, yardages, and fees are approximate seed values for demo purposes -
// confirm green fees, visitor policies, and tee sheet windows with the course
// before relying on them. UK clubs in particular run ballots, visitor-day
// restrictions, and seasonal rates that this catalog does not model.
//
// Every course carries a `traits` block: how hard the course leans on each part
// of a golfer's game (0-100), plus the conditions that shape it. services/courseFit.js
// matches those demands against the golfer's own strokes gained profile to rank
// courses by fit and by training value.

